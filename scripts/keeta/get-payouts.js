/**
 * Keeta Dubai — settlement payout extractor
 *
 * Flow:
 *   1. Playwright loads /web/app/finance (headless) to warm up mtgsig anti-bot token
 *   2. page.evaluate() calls /api/settlement/statement/v2/r/download/task/list
 *      → returns S3 download URLs for settlement Excel files (per shop, per period)
 *   3. Each Excel is downloaded from S3 (no auth — pre-signed URLs)
 *   4. Invoice Details sheet is parsed:
 *        col H = "Payable to Restaurant" (net payout per day)
 *        col J = Billing Cycle (e.g. "2026.07.01~2026.07.07")
 *        col K = Settlement Date (actual bank transfer date)
 *   5. Rows are grouped by (shop_id, billing_cycle) → sum col H → 1 record per settlement
 *   6. POST each record to /api/keeta/portal-payout-record (backend deduplicates by payout_id)
 *
 * Session note: mtgsig is generated by H5guard JS running inside the browser.
 * Direct HTTP without it returns 403 on the download/task/list endpoint.
 * The session token (cookies) is valid until 2027-02.
 *
 * Usage (local):
 *   WEBHOOK_URL=https://sushizen-shift-app-038d846023bc.herokuapp.com \
 *   SESSION_PATH=scripts/keeta/keeta-session.b64.txt \
 *   node scripts/keeta/get-payouts.js
 *
 * Usage (CI):
 *   KEETA_SESSION=<base64> WEBHOOK_URL=... node scripts/keeta/get-payouts.js
 */

const { chromium }  = require('playwright');
const fs            = require('fs');
const path          = require('path');
const zlib          = require('zlib');
const xlsx          = require('xlsx');  // npm install xlsx

const WEBHOOK_URL   = process.env.WEBHOOK_URL;
const PORTAL        = 'https://merchant.mykeeta.com';

// Shop ID → store code mapping (Keeta portal shopIds)
// Which brand this run's session belongs to. Keeta gives each brand its own login,
// so the account decides the brand — the settlement report itself never says it.
const KEETA_BRAND = (process.env.KEETA_BRAND || 'sushi_zen').trim().toLowerCase();

const BRAND_PREFIX = { sushi_zen: 'SZ', ramen_zen: 'RZ', all_veggie: 'AVS' };

// The portal's shop label ("Arjan") → the branch code the rest of the OS uses.
const BRANCH_FROM_LABEL = [
  [/arjan/i,                    'ARJ'],
  [/barsha\s*3|al\s*barsha/i,   'AB3'],
  [/business\s*bay/i,           'BB'],
  [/jumeirah|jlt/i,             'JLT'],
  [/al\s*mina|mina/i,           'AM'],
  [/mirdif|mc/i,                'MC'],
];

function branchFromLabel(label) {
  for (const [re, code] of BRANCH_FROM_LABEL) if (re.test(label || '')) return code;
  return '';
}

/**
 * Identify a shop. SHOP_MAP wins so existing store codes never move; anything else is
 * built from this run's brand plus the label in the report. Skipping unknown shops is
 * what silently lost an entire brand's payouts, so only give up when the label cannot
 * be recognised either — and say so loudly.
 */
function resolveShop(shopId, shopLabel) {
  const known = SHOP_MAP[shopId];
  if (known) return known;
  const prefix = BRAND_PREFIX[KEETA_BRAND];
  const branch = branchFromLabel(shopLabel);
  if (!prefix || !branch) return null;
  return {
    code:  `KEETA_${prefix}_${branch}`,
    name:  `${KEETA_BRAND} ${shopLabel}`.trim(),
    brand: KEETA_BRAND,
    derived: true,
  };
}

